from __future__ import annotations
from typing import (
    TYPE_CHECKING,
    Any,
    Self,
    TypeVar,
    Protocol,
    SupportsIndex,
    overload,
)
from collections.abc import Iterable, Callable, Iterator

if TYPE_CHECKING:
    import sys

    A = TypeVar("A")

    class SupportsDunderLT(Protocol[A]):  # type: ignore
        def __lt__(self, other: A) -> bool: ...

    class SupportsDunderGT(Protocol[A]):  # type: ignore
        def __gt__(self, other: A) -> bool: ...

    SupportsRichComparison = SupportsDunderLT[Any] | SupportsDunderGT[Any]

    T = TypeVar("T", contravariant=True)

    class MutableOnlyList(Protocol[T]):  # type: ignore
        """
        A contravariant list type.

        Elements can be added and modified, but cannot be extracted.

        Think of `MutableOnlyList[X]` as a list containing elements of
        type `X` and possibly other types. However, you can only add elements of
        type `X` or its subtypes.

        The concern is that the list could have been passed to a function that
        added elements of some other type `Y`, which is why you cannot extract
        elements from it.

        A function that accepts `MutableOnlyList[X]` may add elements
        of type `X` or its subtypes.
        """

        @overload
        def __setitem__(self, index: SupportsIndex, value: T, /) -> None: ...
        @overload
        def __setitem__(
            self, index: slice[Any, Any, Any], value: Iterable[T], /
        ) -> None: ...
        def __delitem__(self, index: SupportsIndex, /) -> None: ...
        def __len__(self) -> int: ...

        # def __iter__(self) -> Iterator[T]: ...
        def __contains__(self, item: Any, /) -> bool: ...
        def __reversed__(self) -> Iterable[T]: ...
        def __add__(self, other: Self, /) -> Self: ...
        def __mul__(self, times: SupportsIndex, /) -> Self: ...
        def __rmul__(self, times: SupportsIndex, /) -> Self: ...
        def __iadd__(self, other: Iterable[T], /) -> Self: ...
        def __imul__(self, times: SupportsIndex, /) -> Self: ...
        def __le__(self, other: Self, /) -> bool: ...
        def __lt__(self, other: Self, /) -> bool: ...
        def append(self, item: T, /) -> None: ...
        def clear(self) -> None: ...
        def copy(self) -> Self: ...
        def count(self, item: T, /) -> int: ...
        def extend(self, iterable: Iterable[T], /) -> None: ...
        def index(
            self, item: T, start: SupportsIndex = 0, end: SupportsIndex = sys.maxsize, /
        ) -> int: ...
        def insert(self, index: SupportsIndex, item: T, /) -> None: ...
        def remove(self, item: T, /) -> None: ...
        def reverse(self) -> None: ...
        @overload
        def sort(
            self: SupportsRichComparison,
            *,
            key: None = None,
            reverse: bool = False,
        ) -> None: ...
        @overload
        def sort(
            self,
            *,
            key: Callable[[T], SupportsRichComparison],
            reverse: bool = False,
        ) -> None: ...

    U = TypeVar("U", covariant=True)

    class ReadOnlyList(Protocol[U]):  # type: ignore
        """
        A covariant list type.

        Elements can be extracted, but cannot be added or modified.

        list.append, list.count, list.extend, list.index, list.insert, list.remove,
        are not supported.

        Think of `ReadOnlyList[X]` as a list containing only elements of
        type `X` and potentially its subtypes. So if you extract an element from
        it, you can be sure that it is of type `X`.

        The concern is that the list might in fact contain only elements of some
        type `Y` which is a subtype of `X`. Adding an element of type `X` would
        then be problematic if its reference is used elsewhere that expects only
        elements of type `Y`.

        A function that accepts `ReadOnlyList[X]` can obtain elements
        of type `X`, and guarantees that it will not add elements.
        """

        @overload
        def __getitem__(self, index: SupportsIndex, /) -> U: ...
        @overload
        def __getitem__(self, index: slice[Any, Any, Any], /) -> Self: ...
        def __delitem__(
            self, index: SupportsIndex | slice[Any, Any, Any], /
        ) -> None: ...
        def __len__(self) -> int: ...
        def __iter__(self) -> Iterator[U]: ...
        def __contains__(self, item: Any, /) -> bool: ...
        def __reversed__(self) -> Iterable[U]: ...
        def __add__(self, other: Self, /) -> Self: ...
        def __mul__(self, times: SupportsIndex, /) -> Self: ...
        def __rmul__(self, times: SupportsIndex, /) -> Self: ...
        def __iadd__(self, other: Iterable[U], /) -> Self: ...
        def __imul__(self, times: SupportsIndex, /) -> Self: ...
        def __le__(self, other: Self, /) -> bool: ...
        def __lt__(self, other: Self, /) -> bool: ...
        def clear(self) -> None: ...
        def copy(self) -> Self: ...
        def pop(self, index: SupportsIndex = -1, /) -> U: ...
        def reverse(self) -> None: ...
        @overload
        def sort(
            self: SupportsRichComparison,
            *,
            key: None = None,
            reverse: bool = False,
        ) -> None: ...
        @overload
        def sort(
            self,
            *,
            key: Callable[[U], SupportsRichComparison],
            reverse: bool = False,
        ) -> None: ...
